import "server-only";

import { NextResponse } from "next/server";
import { idempotencyKeyOf, type GenerationKind } from "./idempotency";
import { claimGeneration, findReplay, hashBody, releaseGeneration, storeResult } from "./result-cache";

/**
 * The same five steps in each document route, so each route adds a handful of
 * lines rather than its own copy of the rules (see `./result-cache` for why):
 *
 * 1. `readIdempotentRequest` — the body read once, as text, for its hash.
 * 2. `replayOf` — before anything is reserved: a finished result for this
 *    exact request is answered as is, with no grant and no model call.
 * 3. `claim` — after the grant: another request generating under this key
 *    right now gets a 409 (`busy`) instead of paying for a second CV.
 * 4. `remember` — on success, before the response goes out.
 * 5. `forget` — on failure, so the key can be used again at once.
 *
 * A request without a key skips all of it and behaves as before.
 */

export type IdempotentRequest = {
  key: string | null;
  kind: GenerationKind;
  bodyHash: string;
  raw: string;
};

export async function readIdempotentRequest(request: Request, kind: GenerationKind): Promise<IdempotentRequest> {
  const raw = await request.text().catch(() => "");
  return { key: idempotencyKeyOf(request.headers), kind, bodyHash: hashBody(raw), raw };
}

/** The body as JSON, or null — what `request.json().catch(() => null)` used to give. */
export function parseBody(request: IdempotentRequest): unknown {
  try {
    return JSON.parse(request.raw);
  } catch {
    return null;
  }
}

export async function replayOf(request: IdempotentRequest): Promise<unknown | null> {
  if (!request.key) return null;
  const found = await findReplay(request.key, request.kind, request.bodyHash);
  return found ? found.value : null;
}

/** False when the key is being generated by another request right now. */
export async function claim(request: IdempotentRequest): Promise<boolean> {
  if (!request.key) return true;
  return (await claimGeneration(request.key, request.kind, request.bodyHash)) !== "busy";
}

export async function remember(request: IdempotentRequest, value: unknown, extra: { jobText?: string } = {}): Promise<void> {
  if (!request.key) return;
  await storeResult(request.key, request.kind, request.bodyHash, { value, ...extra });
}

export async function forget(request: IdempotentRequest): Promise<void> {
  if (!request.key) return;
  await releaseGeneration(request.key);
}

/** The answer to a second request under a key still being generated. The browser polls `GET /api/generate/result`. */
export function busyResponse(): NextResponse {
  return NextResponse.json(
    {
      error: "Todavía estamos terminando esta misma generación. En unos segundos la traemos.",
      reason: "in_progress",
    },
    { status: 409 },
  );
}

/** A replayed JSON answer, marked as such for the logs and the tests. */
export function replayJson(value: unknown): NextResponse {
  return NextResponse.json(value, { headers: { "x-cvp-replayed": "1", "cache-control": "no-store" } });
}

/** A replayed streaming answer: the single `done` frame a reader waits for. */
export function replayStream(value: unknown): Response {
  const body = new TextEncoder().encode(`${JSON.stringify({ type: "done", value })}\n`);
  return new Response(body, {
    headers: {
      "content-type": "application/x-ndjson; charset=utf-8",
      "cache-control": "no-store",
      "x-cvp-replayed": "1",
    },
  });
}
