import {
  buildEvidenceIndex,
  buildIndexFrom,
  normalize,
  statedHardTerms,
  supports,
} from "@/lib/ai/evidence";
import type { CVDocument } from "@/lib/schemas/cv";
import type { JobAnalysis } from "@/lib/schemas/job";
import type { Profile } from "@/lib/schemas/profile";
import { PRACTICAL_FACTS, practicalFactFor, type PracticalFact } from "@/lib/profile/practical-facts";

export { PRACTICAL_FACTS, practicalFactFor, type PracticalFact };

/**
 * The candidate's pairs-section facts and the product's two jobs with them:
 * require the practical ones (availability, licence, vehicle, work
 * eligibility) verbatim in the prompt and impose them on the response
 * afterwards, and — outside the candidate's field — strip whatever technical
 * credential got through despite never being asked for. See
 * `withProfilePractical` for the first and `withoutOffFieldCredentials` for
 * the second. The facts themselves — the field list, their regexes,
 * `practicalFactFor` — live in `lib/profile/practical-facts.ts`, re-exported
 * here: that file has no dependency on this one's `lib/ai/evidence` neighbour,
 * which is what lets the deterministic CV parser read a "Disponibilidad: …"
 * line into `profile.practical` without pulling the AI layer into the
 * onboarding bundle.
 *
 * These are the fields the model gets wrong most often and most expensively.
 * Measured over the 5 applications in `public/cvexact-2026-08-17.json`
 * generated by one model, 4 of them declared an availability the profile never
 * stated, and every one of the four was the posting's own hours mirrored back as
 * a fact about the candidate:
 *
 *   posting "jueves a domingo de 19:30hs al cierre" → CV "Jueves a domingo, 19:30hs al cierre"
 *   posting "disponibilidad los sábados"            → CV "Lunes a sábados, full time o part time"
 *   posting "1 a 2 horas diarias"                   → CV "1–2 horas diarias (mañanas)"
 *
 * against a profile that says, in all three cases, "Full time, Part time". A
 * recruiter scanning a pairs row reads it as a commitment, so this is not a
 * wording problem: it books the candidate into a schedule they never agreed to.
 *
 * `BUILD_CV_SYSTEM` has forbidden it in as many words since the `unrelated`
 * strategy was written ("THE AVAILABILITY IS THE CANDIDATE'S, NOT THE
 * POSTING'S"), and `verifyPairs` has reported it as an error for as long. The
 * instruction lost anyway, which is what makes this the same class of problem as
 * `header`: a value that exists verbatim in the profile should be copied, not
 * requested. See `withProfilePractical`.
 *
 * Deliberately free of `server-only`: the route imposes these facts and the CV
 * editor offers "use the value from my profile" as a one-click fix on a finding,
 * so the same function has to run in both places.
 */

/**
 * What the profile says about `fact`, or `null` when it says nothing.
 *
 * A `flag` in `false` is "nothing": the user has not ticked the box, and a CV is
 * not the place to volunteer that they lack a vehicle.
 */
export function statedPractical(profile: Profile, fact: PracticalFact): string | null {
  const value = profile.practical[fact.field];
  if (typeof value === "boolean") return value ? "true" : null;
  const trimmed = String(value ?? "").trim();
  return trimmed || null;
}

/**
 * The practical facts this posting asks about and the profile answers.
 *
 * Used to require the rows in the prompt rather than hope for them, exactly as
 * `matchedCredentials` does for certifications and languages — and for the same
 * measured reason: a section that is optional in a prompt this long is a section
 * that does not exist.
 */
/**
 * @param jobText The posting as pasted, when the caller has it.
 *
 * The analysis alone was not enough. A posting whose first three lines read
 * "Contrato por tiempo indeterminado / Jornada completa / Presencial y remoto"
 * put none of them in `requirements` — they sit above the "Requisitos:" heading,
 * and the extractor is told to read the posting literally, not to promote its
 * masthead. So the candidate's availability, which the posting asks about in as
 * many words, never reached the REQUIRED PAIRS block and the CV came back
 * without it.
 *
 * Reading the raw text closes that without asking the model to classify
 * anything: `PRACTICAL_FACTS[].asks` already matches "jornada" and "full time",
 * it just had nowhere to find them.
 *
 * Outside the candidate's field, `fact.asks` is not even asked: every fact the
 * profile states is required, whether or not the posting's own words happen to
 * match the regex. `STRATEGIES.unrelated` already says availability, licence
 * and vehicle "are frequently the deciding factors" here, and a four-line
 * posting ("Buscamos técnico instalador... enviar cv") states no schedule and
 * asks nothing `fact.asks` can match, but a candidate with a car is still a
 * better lead for a field job than one without, and the profile is the only
 * place that fact lives. Requiring it outright is safe in a way it is not for
 * `direct`: this reader wants every practical fact volunteered regardless of
 * whether the ad happened to ask, where a software posting that never
 * mentions relocation has no use for a relocation row.
 */
export function practicalAsks(
  profile: Profile,
  analysis: JobAnalysis,
  jobText?: string,
): PracticalFact[] {
  if (analysis.relevance === "unrelated") {
    return PRACTICAL_FACTS.filter((fact) => statedPractical(profile, fact) !== null);
  }

  const posting = normalize(
    [
      analysis.title,
      analysis.domain,
      ...analysis.keywords,
      ...analysis.requirements.map((r) => r.text),
      ...analysis.responsibilities,
      jobText ?? "",
    ].join(" | "),
  );

  return PRACTICAL_FACTS.filter(
    (fact) => fact.asks.test(posting) && statedPractical(profile, fact) !== null,
  );
}

/**
 * The cap on `cvPairItemSchema.value`. `practicalSchema.availability` allows 200
 * characters and a pairs value allows 160, so a long availability has to be cut
 * here or the document this returns stops parsing.
 */
const PAIR_VALUE_MAX = 160;

/**
 * Replaces the value of every practical pairs row with the profile's own.
 *
 * The deterministic half of the fix, and the reason `verifyPairs` should have
 * almost nothing left to report: the same move `headerFromProfile` makes for the
 * contact block, applied to the other fields whose content is copied rather than
 * written. A value the model cannot author is a value it cannot mirror back from
 * the posting.
 *
 * Rows are rewritten, never added: which facts appear, in what order, under what
 * heading and in which language stays the model's call, because all of that is
 * phrasing. Only the value is imposed.
 *
 * A row the profile cannot answer is dropped rather than corrected. There is no
 * honest text to put in it, and a `flag` has no text at all — writing "Sí" here
 * would put a fixed word of the finished document outside `labels` and
 * `section.title`, which is the one thing the renderers are built not to do. So
 * a true flag keeps whatever the model wrote (the fact is true; only its wording
 * is at stake) and a false one loses its row.
 *
 * A pairs section left with no rows disappears through `dropEmptySections` when
 * the document is re-parsed.
 */
export function withProfilePractical(cv: CVDocument, profile: Profile): CVDocument {
  let changed = false;

  const sections = cv.sections.map((section) => {
    if (section.kind !== "pairs") return section;

    const items = section.items.flatMap((item) => {
      const fact = practicalFactFor(item.label);
      if (!fact) return [item];

      const stated = statedPractical(profile, fact);
      if (stated === null) {
        changed = true;
        return [];
      }
      // Nothing to copy, and the fact holds — the model's wording stands.
      if (fact.kind === "flag") return [item];

      const value = stated.slice(0, PAIR_VALUE_MAX);
      if (value === item.value) return [item];
      changed = true;
      return [{ ...item, value }];
    });

    return { ...section, items };
  });

  return changed ? { ...cv, sections } : cv;
}

/**
 * Drops a pairs row naming a technical credential this posting never asked
 * about — the deterministic half of `STRATEGIES.unrelated`'s "STRIP THE
 * JARGON", for the one place a row is safe to delete outright rather than
 * merely warn about.
 *
 * A labelled fact, unlike a bullet, carries no surrounding context that would
 * be lost by dropping it, which is what makes the pairs block different from
 * the rest of the document: a CV for a camera-installer vacancy opened its
 * final section with "AWS Cloud Practitioner" — true, and exactly the signal
 * `STRATEGIES.unrelated` says reads as overqualification and costs interviews.
 * The instruction not to write it lost anyway (same failure `withProfilePractical`
 * exists to fix for availability), so this removes what got through instead of
 * only reporting it after the fact.
 *
 * Only ever removes; never rewrites a value, which stays `withProfilePractical`'s
 * job. A row `practicalFactFor` recognises is left alone here even when it names
 * a hard term — the driving licence "B1" is a hard term by the acronym check,
 * and it is exactly the row this candidate needs on the page, not one to strip.
 *
 * Runs only outside the candidate's field, where naming a stray technology is
 * a defect rather than the point.
 */
export function withoutOffFieldCredentials(
  cv: CVDocument,
  profile: Profile,
  analysis: Pick<
    JobAnalysis,
    "relevance" | "title" | "domain" | "keywords" | "requirements" | "responsibilities"
  >,
): CVDocument {
  if (analysis.relevance !== "unrelated") return cv;

  const evidence = buildEvidenceIndex(profile);
  const posting = buildIndexFrom([
    analysis.title,
    analysis.domain,
    ...analysis.keywords,
    ...analysis.requirements.map((r) => r.text),
    ...analysis.responsibilities,
  ]);

  let changed = false;

  const sections = cv.sections.map((section) => {
    if (section.kind !== "pairs") return section;

    const items = section.items.filter((item) => {
      if (practicalFactFor(item.label)) return true;

      const terms = statedHardTerms(`${item.label} ${item.value}`, evidence);
      const stray = terms.some((term) => !supports(posting, term));
      if (!stray) return true;

      changed = true;
      return false;
    });

    return { ...section, items };
  });

  return changed ? { ...cv, sections } : cv;
}
